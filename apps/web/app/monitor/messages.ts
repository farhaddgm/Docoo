export type MonitorMessages = typeof fa;

export const monitorMessages = (locale: Locale): MonitorMessages => (locale === 'en' ? en : fa);

/** The label of one choice, a per-setting wording first, else the shared one for the value. */
export function optionLabel(messages: MonitorMessages, key: string, value: string): string {
  return (
    messages.optionOverrides[`${key}|${value}`] ?? messages.optionLabels[value as never] ?? value
  );
}

/** Replaces `{name}` placeholders in a sentence. */
export function fillText(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/gu, (match, name: string) => values[name] ?? match);
}

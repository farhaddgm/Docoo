export function businessMessages(locale: Locale) {
  return messages[locale];
}

/** Section titles in the language of the page; unknown keys (new in Contenter) show as they are. */
export function sectionTitle(locale: Locale, key: string): string {
  return messages[locale].profile.sections[key] ?? key;
}

/** A list of names in running text, with the separator of the language. */
export function joinList(locale: Locale, items: readonly string[]): string {
  return items.join(locale === 'fa' ? '، ' : ', ');
}

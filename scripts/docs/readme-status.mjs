// Keeps the status block of README.md true. Facts that change with every release (the version, the
// release date, the number of ADRs and manifest documents) are generated from their source of truth
// instead of being written by hand, so the README cannot fall behind the code again.
//
//   node scripts/docs/readme-status.mjs          rewrite the block
//   node scripts/docs/readme-status.mjs --check  fail when the block is out of date (CI: docs:validate)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const BEGIN =
  '<!-- status:begin (generated by scripts/docs/readme-status.mjs; do not edit) -->';
export const END = '<!-- status:end -->';

const digits = '۰۱۲۳۴۵۶۷۸۹';
const fa = (value) => String(value).replace(/\d/gu, (d) => digits[Number(d)]);

/** The facts of one moment, read from the files that own them. */
export function collectFacts({ packageJson, changelog, manifest, adrFiles }) {
  const version = JSON.parse(packageJson).version;
  const heading = /^## \[(\d+\.\d+\.\d+)\] — (\d{4}-\d{2}-\d{2})$/mu.exec(changelog);
  if (!heading) throw new Error('CHANGELOG.md has no released version heading.');
  if (heading[1] !== version) {
    throw new Error(
      `package.json is ${version} but the newest CHANGELOG release is ${heading[1]}; release them together.`,
    );
  }
  const documents = [...manifest.matchAll(/^\s+- path: /gmu)].length;
  const adrs = adrFiles.filter((name) => /^\d{4}-.+\.md$/u.test(name)).length;
  return { version, date: heading[2], documents, adrs };
}

export function renderBlock(facts) {
  return [
    BEGIN,
    `- نسخهٔ فعلی: ${facts.version} (${facts.date}). فهرست هر نسخه در [CHANGELOG](CHANGELOG.md) است و وضعیت هر قابلیت در [فهرست مستندات](docs/README.md).`,
    `- مستندات: ${fa(facts.documents)} سند در manifest و ${fa(facts.adrs)} تصمیم معماری (ADR) در \`docs/adr\`.`,
    `- هر نیازمندی FR/NFR وضعیت صادقانهٔ خود را در \`qa/traceability.json\` دارد (\`pnpm qa:trace\`).`,
    END,
  ].join('\n');
}

export function replaceBlock(readme, block) {
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error('README.md has no status block; add the begin and end markers.');
  }
  return readme.slice(0, start) + block + readme.slice(end + END.length);
}

async function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const read = (file) => fs.readFile(path.join(root, file), 'utf8');
  const facts = collectFacts({
    packageJson: await read('package.json'),
    changelog: await read('CHANGELOG.md'),
    manifest: await read('docs/_meta/notion-manifest.yaml'),
    adrFiles: await fs.readdir(path.join(root, 'docs/adr')),
  });
  const current = await read('README.md');
  const next = replaceBlock(current, renderBlock(facts));
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error('README.md status block is out of date. Run: pnpm docs:status');
      process.exit(1);
    }
    console.log(`README status block is current (${facts.version}).`);
    return;
  }
  await fs.writeFile(path.join(root, 'README.md'), next);
  console.log(`README status block written (${facts.version}).`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
